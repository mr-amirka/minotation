/**
 * Генератор темы `presetTw4` (D-068): читает эталонный `theme.css` Tailwind из `reference/` и
 * пишет `src/presets/tw4/theme.ts` — переменные темы, версию и SHA-256 источника.
 *
 * Запуск: `node src/presets/tw4/scripts/tw4-theme.mjs` (из `packages/core`). Файл источника не правится руками.
 *
 * Берётся первый блок `@theme default { … }`: переменные `--имя: значение;` (значения в несколько
 * строк склеиваются) и блоки `@keyframes` (тело — сжатой строкой: `animate-spin` выводит их по
 * требованию, как Tailwind). Переменные со служебной функцией Tailwind
 * `--theme(…)` — не CSS, они тоже пропускаются. Блок «Deprecated» (`@theme … reference`) Tailwind
 * в CSS не выводит — не выводим и мы.
 */
import {
  createHash,
} from 'node:crypto';
import {
  readFileSync, writeFileSync,
} from 'node:fs';
import {
  dirname, join,
} from 'node:path';
import {
  fileURLToPath,
} from 'node:url';
import {
  execFileSync,
} from 'node:child_process';
import {
  repeatedConstants,
} from './repeated-constants.mjs';

const PARENT_DIR = '..';

const VERSION = '4.3.3';
const root = join(dirname(fileURLToPath(import.meta.url)), PARENT_DIR, PARENT_DIR, PARENT_DIR, PARENT_DIR);
const source = join(root, 'reference', 'tailwindcss-' + VERSION, 'theme.css');
const target = join(root, 'src', 'presets', 'tw4', 'theme.ts');

const css = readFileSync(source, 'utf8');
const sha256 = createHash('sha256').update(css).digest('hex');

const start = css.indexOf('@theme default {');
if (start < 0) {
  throw new Error('tw4-theme: "@theme default {" not found in ' + source);
}
const theme = {};
const keyframes = {};
let depth = 0;
let i = css.indexOf('{', start) + 1;
let statement = '';
let frames;
let framesStart = 0;
for (; i < css.length; i++) {
  const ch = css[i];
  if (ch === '{') {
    // `@keyframes имя {` на верхнем уровне темы — запоминаем имя и начало тела.
    depth || (frames = /^@keyframes\s+([\w-]+)$/.exec(statement.trim()), framesStart = i + 1);
    depth++;
    statement = '';
  } else if (ch === '}') {
    if (!depth) {
      break;
    }
    depth--;
    depth || !frames || (keyframes[frames[1]] = minify(css.slice(framesStart, i)), frames = undefined);
    statement = '';
  } else if (ch === ';' && !depth) {
    const text = statement.trim();
    const colon = text.indexOf(':');
    if (text.startsWith('--') && colon > 0) {
      const value = text.slice(colon + 1).replace(/\s+/g, ' ').trim();
      value.includes('--theme(') || (theme[text.slice(0, colon).trim()] = value);
    }
    statement = '';
  } else if (!depth) {
    statement += ch;
  }
}

/** Тело `@keyframes` одной строкой: без лишних пробелов и последней `;` блока. */
function minify(text) {
  return text.replace(/\s+/g, ' ').replace(/\s*([{};:,])\s*/g, '$1').replace(/;}/g, '}').trim();
}

const names = Object.keys(theme);
// A value written 3+ times is a constant (lab/no-repeated-string, lab D-017.3); the variables' names are keys
const {
  value,
  body: constantsBody,
} = repeatedConstants([...names.map((name) => theme[name]), ...Object.keys(keyframes).map((name) => keyframes[name])],
  ['TW4_VERSION', 'TW4_THEME_SHA256', 'TW4_THEME', 'TW4_KEYFRAMES']);
const framesBody = Object.keys(keyframes).map((name) => '  ' + JSON.stringify(name) + ': ' + value(keyframes[name]) + ',')
  .join('\n');
const body = names.map((name) => '  ' + JSON.stringify(name) + ': ' + value(theme[name]) + ',').join('\n');
writeFileSync(target, `/**
 * Tailwind ${VERSION} theme for \`presetTw4\` (D-068). Generated by \`scripts/tw4-theme.mjs\` from
 * \`reference/tailwindcss-${VERSION}/theme.css\` (MIT, (c) Tailwind Labs) — do not edit by hand.
 */

/** Tailwind version the theme was taken from. */
export const TW4_VERSION = '${VERSION}';

/** SHA-256 of the source file: a test compares it with \`reference/\` so the theme can't drift. */
export const TW4_THEME_SHA256 = '${sha256}';

/** The values the theme writes 3+ times. */
${constantsBody}

/** Theme variables: name → value, as in \`theme.css\`. */
export const TW4_THEME: Record<string, string> = {
${body}
};

/** Theme \`@keyframes\`: name → body (\`to{transform:rotate(360deg)}\`), emitted on demand by \`animate-*\`. */
export const TW4_KEYFRAMES: Record<string, string> = {
${framesBody}
};
`);
// Стиль проекта — тем же линтером, что и весь код.
execFileSync('npx', ['eslint', '--fix', target], {
  cwd: root,
  stdio: 'inherit',
});
console.log('tw4-theme: ' + names.length + ' variables, ' + Object.keys(keyframes).length + ' keyframes → ' + target);
